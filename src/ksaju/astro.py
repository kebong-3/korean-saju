def _series(terms, tau):
    return sum(a * math.cos(b + c * tau) for a, b, c in terms)


def sun_apparent_longitude(jde: float) -> float:
    """역학시(JDE)에서의 태양 시황경(도, 0~360)."""
    tau = (jde - 2451545.0) / 365250.0
    L = (_series(_L0, tau) + _series(_L1, tau) * tau + _series(_L2, tau) * tau**2
         + _series(_L3, tau) * tau**3 + _series(_L4, tau) * tau**4
         + _series(_L5, tau) * tau**5) / 1e8
    R = (_series(_R0, tau) + _series(_R1, tau) * tau + _series(_R2, tau) * tau**2) / 1e8
    lon = math.degrees(L) + 180.0
    T = tau * 10
    # FK5 보정
    lon += -0.09033 / 3600
    # 장동(황경 방향) — 주요 4항
    om = math.radians(125.04452 - 1934.136261 * T)
    ls = math.radians(280.4665 + 36000.7698 * T)
    lm = math.radians(218.3165 + 481267.8813 * T)
    dpsi = (-17.20 * math.sin(om) - 1.32 * math.sin(2 * ls)
            - 0.23 * math.sin(2 * lm) + 0.21 * math.sin(2 * om))
    lon += dpsi / 3600
    # 광행차
    lon += -20.4898 / 3600 / R
    return lon % 360.0


def sun_longitude_at(dt_utc: datetime) -> float:
    return sun_apparent_longitude(_jde_from_jd(jd_from_datetime(dt_utc)))


def solar_term_jde(target_deg: float, jde_guess: float) -> float:
    """태양 황경이 target_deg 가 되는 JDE (jde_guess 근처)."""
    jde = jde_guess
    for _ in range(50):
        diff = (target_deg - sun_apparent_longitude(jde) + 180) % 360 - 180
        jde += diff * 365.2422 / 360
        if abs(diff) < 1e-7:
            break
    return jde


def solar_term_utc(year: int, target_deg: float) -> datetime:
    """해당 그레고리력 연도에 태양 황경이 target_deg 가 되는 순간 (UTC)."""
    # 춘분(0°)≈3/20. 황경 기준으로 대략적 날짜 추정
    days_from_equinox = ((target_deg % 360)) * 365.2422 / 360
    guess_dt = datetime(year, 3, 20) + timedelta(days=days_from_equinox)
    if guess_dt.year > year:  # 1~3월 절기(소한·대한·입춘·우수·경칩)
        guess_dt = guess_dt.replace(year=year)
    jde = solar_term_jde(target_deg, _jde_from_jd(jd_from_datetime(guess_dt)))
    return datetime_from_jd(_jd_from_jde(jde))


