"""천문 계산: 태양 황경(절기)과 합삭(음력 초하루).

- 태양 황경: VSOP87 지구 급수(Meeus, *Astronomical Algorithms* 부록 III 축약판)
  + FK5 보정 + 장동 + 광행차. 정확도 약 1초각 → 절입 시각 오차 수십 초 이내.
- 합삭: Meeus 49장 (주요 항 + 행성 섭동 14항). 오차 수십 초 이내.
- ΔT: Espenak & Meeus(2006) 다항식.

외부 라이브러리 없이 표준 math 만 사용한다.
"""
