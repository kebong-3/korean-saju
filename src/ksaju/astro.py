def new_moon_jde(k: int) -> float:
    """k번째 합삭(k=0 → 2000-01-06 부근)의 JDE."""
    T = k / 1236.85
    jde = (2451550.09766 + 29.530588861 * k + 0.00015437 * T**2
           - 0.000000150 * T**3 + 0.00000000073 * T**4)
    E = 1 - 0.002516 * T - 0.0000074 * T**2
    r = math.radians
    M = r(2.5534 + 29.10535670 * k - 0.0000014 * T**2 - 0.00000011 * T**3)
    Mp = r(201.5643 + 385.81693528 * k + 0.0107582 * T**2 + 0.00001238 * T**3 - 0.000000058 * T**4)
    F = r(160.7108 + 390.67050284 * k - 0.0016118 * T**2 - 0.00000227 * T**3 + 0.000000011 * T**4)
    Om = r(124.7746 - 1.56375588 * k + 0.0020672 * T**2 + 0.00000215 * T**3)
    s = math.sin
    corr = (-0.40720 * s(Mp) + 0.17241 * E * s(M) + 0.01608 * s(2 * Mp) + 0.01039 * s(2 * F)
            + 0.00739 * E * s(Mp - M) - 0.00514 * E * s(Mp + M) + 0.00208 * E * E * s(2 * M)
            - 0.00111 * s(Mp - 2 * F) - 0.00057 * s(Mp + 2 * F) + 0.00056 * E * s(2 * Mp + M)
            - 0.00042 * s(3 * Mp) + 0.00042 * E * s(M + 2 * F) + 0.00038 * E * s(M - 2 * F)
            - 0.00024 * E * s(2 * Mp - M) - 0.00017 * s(Om) - 0.00007 * s(Mp + 2 * M)
            + 0.00004 * s(2 * Mp - 2 * F) + 0.00004 * s(3 * M) + 0.00003 * s(Mp + M - 2 * F)
            + 0.00003 * s(2 * Mp + 2 * F) - 0.00003 * s(Mp + M + 2 * F)
            + 0.00003 * s(Mp - M + 2 * F) - 0.00002 * s(Mp - M - 2 * F)
            - 0.00002 * s(3 * Mp + M) + 0.00002 * s(4 * Mp))
    pl = 0.0
    for i, (a, b, c) in enumerate(_PLANETARY):
        arg = a + b * k - (0.009173 * T**2 if i == 0 else 0)
        pl += c * math.sin(r(arg))
    return jde + corr + pl


def new_moon_utc(k: int) -> datetime:
    return datetime_from_jd(_jd_from_jde(new_moon_jde(k)))


def new_moon_k_near(dt_utc: datetime) -> int:
    """dt 근처의 합삭 번호 k."""
    return round((jd_from_datetime(dt_utc) - 2451550.09766) / 29.530588861)


def equation_of_time_minutes(dt_utc: datetime) -> float:
    """균시차(분): 진태양시 = 평태양시 + EoT. (근사식, ±30초)"""
    n = dt_utc.timetuple().tm_yday
    b = 2 * math.pi * (n - 81) / 364
    return 9.87 * math.sin(2 * b) - 7.53 * math.cos(b) - 1.5 * math.sin(b)
