def jd_from_datetime(dt: datetime) -> float:
    """naive UTC datetime → 율리우스일(UT)."""
    y, m = dt.year, dt.month
    d = dt.day + (dt.hour + dt.minute / 60 + dt.second / 3600 + dt.microsecond / 3.6e9) / 24
    if m <= 2:
        y -= 1
        m += 12
    a = y // 100
    b = 2 - a + a // 4
    return int(365.25 * (y + 4716)) + int(30.6001 * (m + 1)) + d + b - 1524.5


_JD_UNIX = 2440587.5
_EPOCH = datetime(1970, 1, 1)


def datetime_from_jd(jd: float) -> datetime:
    """율리우스일(UT) → naive UTC datetime (초 단위 반올림)."""
    return _EPOCH + timedelta(seconds=round((jd - _JD_UNIX) * 86400))


def delta_t(year: float) -> float:
    """ΔT = TT − UT (초)."""
    y = year
    if 1900 <= y < 1920:
        t = y - 1900
        return -2.79 + 1.494119 * t - 0.0598939 * t**2 + 0.0061966 * t**3 - 0.000197 * t**4
    if 1920 <= y < 1941:
        t = y - 1920
        return 21.20 + 0.84493 * t - 0.076100 * t**2 + 0.0020936 * t**3
    if 1941 <= y < 1961:
        t = y - 1950
        return 29.07 + 0.407 * t - t**2 / 233 + t**3 / 2547
    if 1961 <= y < 1986:
        t = y - 1975
        return 45.45 + 1.067 * t - t**2 / 260 - t**3 / 718
    if 1986 <= y < 2005:
        t = y - 2000
        return (63.86 + 0.3345 * t - 0.060374 * t**2 + 0.0017275 * t**3
                + 0.000651814 * t**4 + 0.00002373599 * t**5)
    if 2005 <= y < 2050:
        t = y - 2000
        return 62.92 + 0.32217 * t + 0.005589 * t**2
    if 2050 <= y < 2150:
        u = (y - 1820) / 100
        return -20 + 32 * u * u - 0.5628 * (2150 - y)
    if 1800 <= y < 1900:
        t = y - 1900
        return (-2.50 + 228.95 * (t / 100) + 5218.61 * (t / 100) ** 2)  # 거친 근사
    u = (y - 1820) / 100
    return -20 + 32 * u * u


def _jde_from_jd(jd: float) -> float:
    year = 2000 + (jd - 2451545.0) / 365.25
    return jd + delta_t(year) / 86400


def _jd_from_jde(jde: float) -> float:
    year = 2000 + (jde - 2451545.0) / 365.25
    return jde - delta_t(year) / 86400


