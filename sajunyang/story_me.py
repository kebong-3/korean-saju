def _is_hangul(ch: str) -> bool:
    return "가" <= ch <= "힣"


def _final(word: str) -> tuple:
    """(받침 있음, ㄹ받침) — 괄호 속 읽기·한자 독음·숫자·%를 고려한다."""
    w = str(word).rstrip(" '\"’”」』")
    if w.endswith(")") and "(" in w:
        i = w.rfind("(")
        inner, before = w[i + 1:-1], w[:i].rstrip()
        k = 0  # 괄호 바로 앞 한자 개수
        while k < len(before) and before[-1 - k] in _HANJA_READ:
            k += 1
        if k and inner and all(_is_hangul(ch) for ch in inner) and len(inner) == k:
            w = inner  # 癸酉(계유) → 독음
        else:
            w = before  # 금(金), 癸(편인), 편관격(칠살격) → 괄호 앞 말
    if not w:
        return False, False
    ch = w[-1]
    if _is_hangul(ch):
        code = (ord(ch) - 0xAC00) % 28
        return code != 0, code == 8
    if ch in _HANJA_READ:
        return _final(_HANJA_READ[ch])
    if ch in _DIGIT_BAT:
        return _DIGIT_BAT[ch]
    return False, False  # %, 영문 등은 모음으로 끝난다고 본다(퍼센트)


def jo(word, pair: str) -> str:
    """jo('금(金)', '은/는') → '금(金)은'. pair 예: 이/가, 은/는, 을/를, 과/와, 으로/로, 이라/라, 이다냥/다냥."""
    a, b = pair.split("/")
    bat, rieul = _final(word)
    if a.startswith("으로"):
        return f"{word}{b if (not bat or rieul) else a}"
    return f"{word}{a if bat else b}"


def pct(v: float) -> str:
    s = f"{float(v):.1f}"
    if s.endswith(".0"):
        s = s[:-2]
    return s + "%"


def nsent(t: str) -> int:
    """문장 수(마침표·물음표·느낌표 기준)."""
    return sum(1 for i, ch in enumerate(t) if ch in ".!?" and (i + 1 == len(t) or t[i + 1] == " "))


def add(p: str, extra: str, limit: int = 5) -> str:
    """문단이 limit 문장을 넘지 않을 때만 extra를 덧붙인다."""
    if not extra or nsent(p) + nsent(extra) > limit:
        return p
    return f"{p} {extra}"


