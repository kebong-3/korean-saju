def _parse_member(m: str) -> tuple:
    parts = m.split()
    if len(parts) == 2 and len(parts[0]) == 2:
        return parts[0][0], parts[0][1], parts[1]  # 위치, 간/지, 글자
    return None, None, m.strip()


def _char_idx(ch: str) -> int:
    return STEMS.index(ch) if ch in STEMS else BRANCHES.index(ch) + 10 if ch in BRANCHES else 99


def _read(ch: str) -> str:
    return f"{ch}({_HANJA_READ.get(ch, '')})" if ch in _HANJA_READ else ch


