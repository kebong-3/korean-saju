_UNWED = [("배우자의 자리", "연인의 자리"), ("배우자 자리", "인연 자리"), ("배우자 곁", "연인 곁"), ("나·배우자", "나·연인"),
          ("자신·배우자", "자신·연인"), ("배우자 별", "인연 별"), ("배우자궁", "인연궁"), ("남편·연인", "연인"), ("아내·연인", "연인")]


def _unwed(obj):
    """기혼이 아닌 사람에겐 '배우자' 대신 '연인·인연'으로."""
    if isinstance(obj, str):
        for a, b in _UNWED:
            obj = obj.replace(a, b)
        return obj
    if isinstance(obj, list):
        return [_unwed(v) for v in obj]
    if isinstance(obj, dict):
        return {k: _unwed(v) for k, v in obj.items()}
    return obj


def build(r, name: str = "", prof=None) -> dict:
    """SajuReading → 「내 사주」 이야기책. 형식은 모듈 docstring 참고."""
    x = _Ctx(r, name, prof)
    chapters = [_ch_ilgan(x), _ch_ilju(x), _ch_gangyak(x), _ch_ohaeng(x), _ch_gyeokguk(x), _ch_sipseong(x),
                _ch_yongshin(x), _ch_sinsal(x), _ch_hapchung(x), _ch_inyeon_prof(x) if x.status else _ch_inyeon(x)]
    if x.kids:
        chapters.append(_ch_janyeo(x))
    for ch in chapters:
        meta_core = _core(x, ch)
        tale = ch["story"].pop() if len(ch["story"]) > 1 else ""
        link = _tale_link(x, ch) if tale else ""
        ch["설화"] = f"{tale} {link}".strip()
        ch["핵심"] = meta_core
        ch.pop("_meta", None)
    out = {"핵심": _top_core(x), "한줄": _chips(x), "서문": _seomun(x), "장": chapters, "맺음": _maeum(x)}
    return _unwed(out) if x.status in ("미혼", "연애중", "기타") else out
