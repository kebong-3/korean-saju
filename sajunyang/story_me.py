def _ch_sipseong(x: _Ctx) -> dict:
    gw = x.gw
    lst = ", ".join(f"{g} {pct(gw[g])}" for g in GROUPS)
    vis = []
    for p in ("연", "월", "시"):
        if p in x.pos:
            s = x.pos[p].stem
            vis.append(f"{p}간 {STEMS[s]}({ten_god(x.ds, s)})")
    p1 = ("십성은 나(일간)와 다른 글자 사이의 관계 이름이야. 쉽게 말해 네 마음속 무대에 오르는 다섯 배우지. "
          "나와 내 편(비겁), 재능과 표현(식상), 돈과 현실(재성), 일과 책임(관성), 배움과 도움(인성) — "
          f"네 팔자에선 이 배우들의 출연 비중이 {jo(lst, '으로/로')} 나온다냥. 그중 천간에 얼굴을 내민 배우는 {jo('·'.join(vis), '이야/야')}.")
    order = sorted(GROUPS, key=lambda g: -gw[g])
    top, second = order[0], order[1]
    weak = min(GROUPS, key=lambda g: (gw[g], GROUPS.index(g)))
    p2 = f"주연은 {jo(f'{top}({pct(gw[top])})', '이야/야')}. {GROUP_STRONG[top]}"
    if gw[second] >= 20:
        p2 += f" 그 뒤를 받치는 {jo(f'{second}({pct(gw[second])})', '과/와')}의 조합은 {GROUP_PAIR[frozenset((top, second))]}"
    wv = gw[weak]
    wtxt = f"{weak}({pct(wv)}, 아예 빈자리)" if wv == 0 else f"{weak}({pct(wv)})"
    p3 = f"가장 작은 배역은 {jo(wtxt, '이야/야')}. {GROUP_WEAK[weak]}"
    wrole = x.role.get(x.group_el(weak))
    if wrole in ("용신", "희신"):
        p3 += f" 마침 이 {weak} 기운이 네 {wrole}인 {jo(E(x.group_el(weak)), '과/와')} 이어져 있어서, 채울수록 운이 좋아지는 자리야."
    elif wrole in ("기신", "구신"):
        p3 += f" 이 {weak} 기운은 너에게 부담 쪽({wrole})이라, 적다고 흠이 되진 않아."
    return {"id": "sipseong", "icon": "🎭", "title": "네 안의 다섯 배우, 십성", "term": top,
            "summary": f"주연 {top} {pct(gw[top])} · 빈자리 {weak} {pct(wv)}",
            "story": [p1, p2, p3, GROUP_TALE[top]], "tip": GROUP_TIP[weak]}


