def _day_rel(x: _Ctx) -> tuple:
    """일지가 걸린 원국 내 충·합: ((상대 글자들), (합 상대 글자들))."""
    cl, hp = [], []
    for rel in x.a.relations:
        mem = [m for m in rel.members if m.startswith("일지")]
        if not mem:
            continue
        others = [m.split()[-1] for m in rel.members if not m.startswith("일지")]
        if rel.kind == "충":
            cl += others
        elif rel.kind in ("육합",):
            hp += others
    uniq = lambda xs: tuple(dict.fromkeys(xs))  # noqa: E731
    return uniq(cl), uniq(hp)


def _star_info(x: _Ctx) -> tuple:
    a = x.a
    g = "관성" if x.female else "재성"
    gods = ("정관", "편관") if x.female else ("정재", "편재")
    seen = []
    for p in POS_ORDER:
        if p not in x.pos:
            continue
        if p != "일" and a.ten_gods[p]["천간"] in gods:
            seen.append(f"{p}간 {STEMS[x.pos[p].stem]}({a.ten_gods[p]['천간']})")
        if a.ten_gods[p]["지지"] in gods:
            seen.append(f"{p}지 {BRANCHES[x.pos[p].branch]}({a.ten_gods[p]['지지']})")
    v = x.gw[g]
    state = "none" if v == 0 else "quiet" if (not seen or v < 15) else "balanced" if v < 30 else "many"
    return g, gods, v, seen, state


def _star_years(x: _Ctx, gods) -> tuple:
    now = x.r.today.year + (1 if x.r.today.month >= 10 else 0)
    star, hap = [], []
    for y in x.r.seun:
        if y.year < now:
            continue
        if y.stem_god in gods or y.branch_god in gods:
            star.append(y.year)
        if any("일지" in rl and "합" in rl.split(":")[0] for rl in y.relations):
            hap.append(y.year)
    return star[:3], [h for h in hap if h not in star[:3]][:2]


