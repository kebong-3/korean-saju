class _Ctx:
    """build() 안에서 자주 쓰는 값 모음."""

    def __init__(self, r, name: str, prof=None):
        self.r = r
        prof = prof or {}
        st = str(prof.get("결혼") or "").strip()
        self.status = st if st in ("미혼", "연애중", "기혼", "기타") else ""
        try:
            self.kids = max(0, int(prof.get("자녀") or 0))
        except (TypeError, ValueError):
            self.kids = 0
        self.c = c = r.chart
        self.a = a = r.analysis
        self.name = (name or getattr(c.birth, "name", "") or "").strip()
        self.ds = c.day_stem
        self.de = STEM_ELEMENT[self.ds]
        self.my = ELEMENTS[self.de]
        self.female = c.birth.gender == "여"
        self.pos = {"연": c.year, "월": c.month, "일": c.day}
        if c.hour is not None:
            self.pos["시"] = c.hour
        self.has_hour = c.hour is not None
        self.gw = a.group_weight
        self.ew = a.element_weight
        self.el_of = {"비겁": self.de, "식상": (self.de + 1) % 5, "재성": (self.de + 2) % 5,
                      "관성": (self.de + 3) % 5, "인성": (self.de + 4) % 5}
        self.role = {a.yongshin: "용신", a.huishin: "희신", a.gishin: "기신", a.gushin: "구신", a.hanshin: "한신"}
        sc = a.strength_score
        self.strong_lean = sc >= 55 or (sc > 45 and a.deukryeong)
        if a.strength == "중화":
            self.skey = "중화강" if self.strong_lean else "중화약"
        else:
            self.skey = a.strength

    # 호칭
    @property
    def you(self) -> str:
        return self.name or "너"

    @property
    def you_ui(self) -> str:
        return f"{self.name}의" if self.name else "너의"

    @property
    def you_eun(self) -> str:
        return jo(self.name, "은/는") if self.name else "너는"

    def group_el(self, g: str) -> str:
        return ELEMENTS[self.el_of[g]]


