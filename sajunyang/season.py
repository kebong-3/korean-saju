ORDER = list(DIARY)  # 입춘 → 대한


def current(now_kst: datetime) -> dict:
    """지금 속한 절기와 다음 절기."""
    utc = now_kst - KST
    terms = []
    for y in (utc.year - 1, utc.year, utc.year + 1):
        terms += term_instants(y)
    terms.sort()
    cur = max(t for t in terms if t[0] <= utc)
    nxt = min(t for t in terms if t[0] > utc)
    name, nname = cur[1], nxt[1]
    start, nstart = (cur[0] + KST).date(), (nxt[0] + KST).date()
    emo, diary, tip = DIARY[name]
    return {"이름": name, "이모지": emo, "시작": start.isoformat(), "다음": nname, "다음이모지": DIARY[nname][0],
            "다음날짜": nstart.isoformat(), "남은날": (nstart - now_kst.date()).days, "번호": ORDER.index(name) + 1,
            "일기": diary, "개운": tip, "키": f"{start.year}-{name}"}


def all_terms() -> list[dict]:
    return [{"이름": k, "이모지": v[0]} for k, v in DIARY.items()]


def today_kst() -> date:
    return (datetime.utcnow() + KST).date()
