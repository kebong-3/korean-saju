# ---------------------------------------------------------------- 근거 데이터
def _week(r, today: date) -> list[dict]:
    return F.calendar(r, today, 7)


def _month(r, today: date) -> dict:
    months = wolun(r.chart, today.year if today.month > 1 or today.day >= 6 else today.year - 1)
    cur = None
    for m in months:
        if m.start_kst.date() <= today:
            cur = m
    days = F.calendar(r, today.replace(day=1), 31)
    days = [x for x in days if x["date"][:7] == today.isoformat()[:7]]
    info = {}
    if cur:
        s, rels, stage = F._pillar_score(r.chart, r.analysis, cur.pillar)
        info = {"월운": cur.pillar.hanja + f"({cur.pillar.hangul})", "절기": cur.label, "시작": cur.start_kst.strftime("%m/%d"),
                "십성": f"{cur.stem_god}/{cur.branch_god}", "점수": F._clamp(s), "12운성": stage,
                "작용": [str(x) for x in rels]}
    ranked = sorted(days, key=lambda x: -x["점수"])
    return {"이번달": info, "날짜별": days, "좋은날": [x["date"] for x in ranked[:3]], "조심할날": [x["date"] for x in ranked[-3:]]}


def extra_for(kind: str, r, fx: dict, today: date, day: date | None = None, text: str = "") -> dict:
    if kind == "day":
        d = day or today
        return {"날짜": d.isoformat(), "그날운세": F.day_fortune(r, d), "시간대": F.hourly(r, d)}
    if kind == "week":
        return {"7일": _week(r, today)}
    if kind == "month":
        return _month(r, today)
    if kind in ("love", "money", "career", "health"):
        return {"앞으로10년": fx["앞으로10년"], "신년운세분야": fx["신년운세"]["분야"], "맞춤": fx["맞춤"]}
    if kind == "dream":
        return {"꿈내용": text, "꿈꾼날": F.day_fortune(r, day or today)}
    if kind == "daewoon":
        return {"평생운": fx["평생운"], "앞으로10년": fx["앞으로10년"]}
    return {}


def compact_fortune(fx: dict) -> str:
    y, life, mt, t = fx["신년운세"], fx["평생운"], fx["맞춤"], fx["오늘운세"]
    cur = life["현재"]
