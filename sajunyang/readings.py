def _ga(w: str) -> str:
    """받침에 맞는 주격 조사."""
    return w + ("이" if w and (ord(w[-1]) - 0xAC00) % 28 else "가") if w and "가" <= w[-1] <= "힣" else w + "이(가)"


def _j(x) -> str:
    return " · ".join(x) if isinstance(x, list) else str(x)


def _rel_story(rels: list[str]) -> str:
    if not rels:
        return "원국과 크게 부딪히거나 묶이는 글자가 없어서, 바람이 잔잔한 날이다냥. 이런 날은 평소 하던 일을 차분히 밀고 가면 된다냥."
    good = [x for x in rels if any(k in x for k in ("합",))]
    bad = [x for x in rels if any(k in x for k in ("충", "형", "파", "해", "원진"))]
    s = ""
    if good:
        s += f"{good[0].split(':')[0]}이 들어와서 누군가와 손발이 맞거나 일이 엮여 들어오기 쉽다냥. "
    if bad:
        s += (f"한편 {bad[0].split(':')[0]}의 기운도 있어서, 계획이 한 번쯤 흔들리거나 말이 엇갈릴 수 있다냥. "
              "충은 깨지는 게 아니라 흔들어서 정리하는 거니까, 급하게 결정하지 말고 한 템포 쉬어 가라냥.")
    return s


