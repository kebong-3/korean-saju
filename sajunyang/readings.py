        f"{y['연도']}년 {y['간지']} '{y['테마']}' 총운{y['총운']} " + " ".join(f"{k}{v}" for k, v in y["분야"].items()),
        f"{y['연도']}년 월별점수 " + " ".join(f"{m['월']}월{m['점수']}({m['십성']})" for m in y["월별"])
