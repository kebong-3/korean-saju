        "대운점수 " + " ".join(f"{p['나이']}세{p['간지']}{p['점수']}" for p in life["대운"])
        + (f" | 현재 {cur['나이']}세 대운" if cur else "") + f" | 전성기 {life['전성기']['나이']}세",
        f"맞춤: 직업유형 {mt['직업']['유형']}({mt['직업']['추천']}) 연애 {mt['연애스타일']} 잘맞는띠 {mt['잘맞는띠']}"
