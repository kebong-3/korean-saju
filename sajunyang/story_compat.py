def _branch_kind(a: int, b: int) -> tuple[str, dict]:
    """compat._branch_relation 과 같은 우선순위로 지지 관계를 판정하고 세부 정보를 함께 돌려준다."""
    pair = frozenset((a, b))
    if pair in SIX_COMBINE:
        return "육합", {"el": SIX_COMBINE[pair]}
    for trio, el in THREE_COMBINE:
        if a in trio and b in trio and a != b:
            return "삼합", {"el": el, "wang": trio[1] in (a, b)}
    if len(pair) == 2 and (a - b) % 12 == 6:
        return "충", {}
    if pair in WONJIN:
        return "원진", {"saying": WONJIN_SAYING.get(pair, "")}
    if pair in PUNISH_PAIRS:
        return "형", {"name": PUNISH_PAIRS[pair]}
    if pair in HARM:
        return "해", {}
    if pair in BREAK:
        return "파", {}
    if pair in GWIMUN:
        return "귀문", {}
    if a == b:
        return "같음", {"self": a in SELF_PUNISH}
    return "무관", {}


def _branch_extra(a: int, b: int, primary: str) -> list[str]:
    """우선 관계 외에 함께 겹치는 관계."""
    pair = frozenset((a, b))
    out = []
    if primary != "충" and len(pair) == 2 and (a - b) % 12 == 6:
        out.append("충")
    if primary != "원진" and pair in WONJIN:
        out.append("원진")
    if primary != "형" and pair in PUNISH_PAIRS:
        out.append("형")
    if primary != "해" and pair in HARM:
        out.append("해")
    if primary != "파" and pair in BREAK:
        out.append("파")
    if primary != "귀문" and pair in GWIMUN:
        out.append("귀문")
    return out


def _stem_kind(a: int, b: int) -> str:
    pair = frozenset((a, b))
    if pair in STEM_COMBINE:
        return "합"
    if pair in STEM_CLASH:
        return "충"
    rel = (STEM_ELEMENT[b] - STEM_ELEMENT[a]) % 5
    return {0: "같음", 1: "생12", 4: "생21", 2: "극12", 3: "극21"}[rel]


