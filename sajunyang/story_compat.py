def _luck_good(p: _P) -> str:
    if p.cur is None:
        return ""
    de = ELEMENTS[STEM_ELEMENT[p.cur.pillar.stem]]
    return "용신" if de == p.yong else "희신" if de == p.hui else "기신" if de == p.gi else ""


def _luck_desc(p: _P, same_as: str = "") -> str:
    if p.cur is None:
        if p.first is not None:
            return f"{jo(p.name, '은는')} 아직 첫 대운({p.first.start_year}년 무렵 시작) 전이라, 타고난 원국의 기운으로 지내는 시기다냥."
        return f"{jo(p.name, '은는')} 아직 대운 정보가 뚜렷하지 않다냥."
    grp = TEN_GOD_GROUP[p.cur.stem_god]
    gname, gdesc = LUCK_GROUP[grp]
    de = ELEMENTS[STEM_ELEMENT[p.cur.pillar.stem]]
    good = ("용신" if de == p.yong else "희신" if de == p.hui else "기신" if de == p.gi else "")
    gtxt = {"용신": " 마침 대운 천간이 보약 오행인 용신이라 순풍이 부는 계절이다냥.",
            "희신": " 대운 천간이 보약을 돕는 희신이라 바람이 등 뒤에서 분다냥.",
            "기신": " 대운 천간이 과식 주의 오행인 기신이라 조금 무거운 짐을 진 계절이니, 곁에서 짐을 나눠 들어 주면 큰 힘이 된다냥.",
            "": ""}[good]
    if same_as and good and good == same_as:
        gtxt = (f" 대운 천간 역시 {jo(good, '이라')} 두 사람이 같은 "
                + ("짐을 나눠 지고 있는 셈이다냥." if good == "기신" else "순풍을 함께 맞고 있다냥."))
    if same_as:
        return (f"{p.name}도 {p.cur.start_year}년부터 {p.cur.pillar} 대운, 천간 십성이 {jo(p.cur.stem_god, '이라')} "
                f"같은 '{gname}'을 지나고 있다냥.{gtxt}")
    return (f"{jo(p.name, '은는')} {p.cur.start_year}년부터 {p.cur.pillar} 대운, 천간 십성이 {jo(p.cur.stem_god, '이라')} "
            f"'{gname}'을 지나는 중이다냥. {gdesc}냥.{gtxt}")


