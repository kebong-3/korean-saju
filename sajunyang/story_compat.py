def _ch_tonic(p1: _P, p2: _P, key: str) -> dict:
    n1, n2 = p1.name, p2.name
    f1, f2 = _fills(p1, p2), _fills(p2, p1)
    para1 = (f"용신은 그 사람 사주에 제일 필요한 '보약 오행'이다냥. 궁합에서 재밌는 건, 내 보약을 상대가 갖고 있느냐다냥. "
             + (f"재밌게도 두 사람의 용신이 똑같이 {_nya(ELEMENT_NAME(ELEMENTS.index(p1.yong)) + '(' + p1.yong + ')')}. 같은 보약이 필요한 사이라, 누가 그 보약을 더 많이 쥐고 있는지가 관건이다냥."
                if p1.yong == p2.yong else
                f"{n1}의 용신은 {ELEMENT_NAME(ELEMENTS.index(p1.yong))}({p1.yong}), {n2}의 용신은 {_nya(ELEMENT_NAME(ELEMENTS.index(p2.yong)) + '(' + p2.yong + ')')}."))

    def line(me: _P, other: _P, f: dict) -> str:
        v = other.weight(me.yong)
        s = f"{other.name}의 사주에는 {me.name}의 보약인 {me.yong} 기운이 {_pct(v)}, {_level(v)} 들어 있다냥"
        if f["yong_rich"]:
            s += f". 곁에 있기만 해도 {jo(me.name, '이가')} 기운을 얻는 사이다냥"
        elif v >= 12:
            s += ". 넉넉하진 않아도 함께 있으면 은근히 힘이 된다냥"
        else:
            s += ". 이 보약은 상대에게 기대기보다 생활 속에서 함께 채우는 게 좋겠다냥"
        for text, _ in _fill_phrases(me, other):
            s += ". " + text
        return s + "."

    para2 = line(p1, p2, f1)
    para3 = line(p2, p1, f2)
    good1 = f1["yong_rich"] or any(e != p1.gi for e in f1["filled"])
    good2 = f2["yong_rich"] or any(e != p2.gi for e in f2["filled"])
    if good1 and good2:
        summary = f"서로의 창고에 서로의 보약이 있는 사이 — 함께 있을수록 둘 다 건강해진다냥."
        tale = _pick(TALES["tonic_both"], key, "tonic")
        tip = "'네 덕분에 힘이 난다'는 말을 아끼지 말라냥."
    elif good1 or good2:
        giver, taker = (p2, p1) if good1 else (p1, p2)
        summary = f"{jo(giver.name, '이가')} {taker.name}의 보약 창고가 되어 주는 사이 — 받은 쪽은 다른 방식으로 갚으면 된다냥."
        tale = _pick(TALES["tonic_one"], key, "tonic")
        tip = f"{jo(taker.name, '은는')} 받은 기운을 웃음으로 돌려주면 정산 끝이다냥."
    else:
        summary = "보약을 서로에게서 찾기보다 둘이 함께 밖에서 구해 오는 사이 — 같이 하는 습관이 보약이다냥."
        tale = _pick(TALES["tonic_none"], key, "tonic")
        tip = f"{p1.yong}·{p2.yong} 기운 채우는 데이트 장소를 같이 정해 두라냥." if p1.yong != p2.yong else f"둘의 보약 {p1.yong} 기운 데이트를 정해 두라냥."
    johu_bits = []
    for p in (p1, p2):
        if not p.johu:
            continue
        o = p2 if p is p1 else p1
        season = "여름" if p.johu == "수" else "겨울"
        v = o.weight(p.johu)
        if v >= 15:
            tail = f"{_pct(v)}나 갖고 있어 계절의 온도까지 맞춰 주는 사이다냥"
        else:
            tail = f"{_pct(v)}만 갖고 있어서, 이 기운은 생활 속에서 따로 챙기는 게 좋다냥"
        johu_bits.append(f"{jo(p.name, '은는')} {season}에 태어나 계절 온도를 맞춰 줄 {p.johu} 기운(조후)도 필요한데, "
                         f"{jo(o.name, '이가')} 그 기운을 {tail}.")
    story = [para1, para2, para3]
    if johu_bits:
        story.append("하나 더, 궁통보감식으로 계절의 온도도 보자냥. " + " ".join(johu_bits))
    story.append(tale)
    return {"id": "tonic", "icon": "🍵", "title": "서로의 보약", "summary": summary,
            "story": story, "tip": tip}


