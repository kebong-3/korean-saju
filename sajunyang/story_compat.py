def build(r1, r2, res: dict, names: list) -> dict:
    """두 사람의 SajuReading, read_compatibility 결과, 이름 목록으로 궁합 이야기를 만든다."""
    names = list(names or [])
    while len(names) < 2:
        names.append("")
    nm1 = names[0] if isinstance(names[0], str) else ""
    nm2 = names[1] if isinstance(names[1], str) else ""
    p1 = _P(r1, nm1, "너")
    p2 = _P(r2, nm2, "상대")
    if p1.name == p2.name:
        p2.name = p2.name + "(상대)" if p2.name != "상대" else "상대"
        if p1.name == p2.name:
            p1.name = "너"
    key = f"{p1.c.day.index}-{p2.c.day.index}-{p1.yb}-{p2.yb}-{p1.mb}-{p2.mb}"
    chapters = [
        _ch_nature(p1, p2, key),
        _ch_attraction(p1, p2, key),
        _ch_room(p1, p2, key),
        _ch_tonic(p1, p2, key),
        _ch_rhythm(p1, p2, key),
        _ch_conflict(p1, p2, res, key),
        _ch_date(p1, p2, key),
    ]
    if p1.cur is not None or p2.cur is not None:
        chapters.append(_ch_flow(p1, p2, key))
    for ch in chapters:
        _split_tale(ch)
        ch["핵심"] = _ch_core(ch["id"], p1, p2, res)
    items = []
    for it in res.get("items", []):
        nm = str(it.get("항목", "")).replace("1번", p1.name).replace("2번", p2.name)
        items.append({"항목": nm, "점수": int(it.get("점수", 0)), "이야기": _item_story(it, p1, p2),
                      "한줄": _item_line(it, p1, p2)})
    return {
        "핵심": _top_core(p1, p2, res),
        "한줄": _one_liners(p1, p2, res),
        "제목": _title(p1, p2),
        "서문": _intro(p1, p2, res, key),
        "장": chapters,
        "항목": items,
        "맺음": _closing(p1, p2, res, chapters),
    }
