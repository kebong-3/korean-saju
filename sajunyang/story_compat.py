        for p, g in ((p1, g1), (p2, g2)):
            star = "재성" if p.gender == "남" else "관성"
            if g == star:
                spouse.append(f"{jo(p.name, '은는')} 전통 명리에서 인연을 뜻하는 별({star})이 대운에 떠 있어서 관계에 마음이 많이 쓰이는 시기다냥")
