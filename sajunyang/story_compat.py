_DIGIT_BATCHIM = {"0": True, "1": True, "2": False, "3": True, "4": False, "5": False,
                  "6": True, "7": True, "8": True, "9": False}
_HANJA_READ = dict(zip(STEMS, STEMS_KO))
_HANJA_READ.update(dict(zip(BRANCHES, BRANCHES_KO)))
_HANJA_READ.update({"木": "목", "火": "화", "土": "토", "金": "금", "水": "수"})


def _readable(ch: str) -> bool:
    return ("가" <= ch <= "힣") or ch in _HANJA_READ or ch in _DIGIT_BATCHIM


def _last_sound(word: str) -> tuple[bool, bool]:
    """(받침 있음, 받침이 ㄹ). 끝에 괄호가 붙으면 괄호 앞 글자로 읽고, 앞 글자가 읽을 수 없는 한자면 괄호 속으로 읽는다."""
    w = str(word).rstrip(" *'\"’”.")
    if w.endswith(")") and "(" in w:
        outer = w[:w.rfind("(")].rstrip()
        inner = w[w.rfind("(") + 1:-1].strip()
        if outer and _readable(outer[-1]):
            w = outer
        elif inner:
            w = inner
        else:
            w = outer
    if not w:
        return False, False
    ch = w[-1]
    if ch in _HANJA_READ:
        ch = _HANJA_READ[ch]
    if "가" <= ch <= "힣":
        jong = (ord(ch) - 0xAC00) % 28
        return jong != 0, jong == 8
    if ch in _DIGIT_BATCHIM:
        return _DIGIT_BATCHIM[ch], ch in "178"
    if ch == "%":
        return False, False  # 퍼센트
    if ch.lower() in "lmn":
        return True, ch.lower() == "l"
    return False, False


def jo(word: str, pair: str) -> str:
    """word + 받침에 맞는 조사. pair: '이가', '은는', '을를', '와과', '으로', '이랑', '아야', '이다', '이야', '이라'."""
    w = str(word)
    bat, rieul = _last_sound(w)
    if w in ("너", "나") and pair == "이가":
        return {"너": "네가", "나": "내가"}[w]
    table = {
        "이가": ("이", "가"), "은는": ("은", "는"), "을를": ("을", "를"), "와과": ("과", "와"),
        "이랑": ("이랑", "랑"), "아야": ("아", "야"), "이다": ("이다", "다"), "이야": ("이야", "야"),
        "이라": ("이라", "라"), "이고": ("이고", "고"), "이나": ("이나", "나"), "이며": ("이며", "며"),
    }
    if pair == "으로":
        return w + ("로" if (not bat or rieul) else "으로")
    if pair not in table:
        raise ValueError(pair)
    a, b = table[pair]
    return w + (a if bat else b)


def _nya(word: str) -> str:
    """'…이다냥' / '…다냥'."""
    bat, _ = _last_sound(word)
    return f"{word}{'이다냥' if bat else '다냥'}"


def _quote(word: str, pair: str) -> str:
    """'따옴표 속 말'+조사."""
    return f"'{word}'" + jo(word, pair)[len(word):]


def _pct(x: float) -> str:
    return f"{x:g}%"


def _pt(s: int) -> str:
    return f"+{s}점" if s > 0 else (f"{s}점" if s < 0 else "0점")


def _seed(*keys) -> int:
    return zlib.crc32("|".join(str(k) for k in keys).encode("utf-8"))


def _pick(seq, *keys):
    seq = list(seq)
    return seq[_seed(*keys) % len(seq)]


def _stem(s: int) -> str:
    return f"{STEMS[s]}({STEMS_KO[s]})"


def _br(b: int) -> str:
    return f"{BRANCHES[b]}({BRANCHES_KO[b]})"


