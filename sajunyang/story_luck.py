def _role(a, e: str) -> str:
    return {a.yongshin: "용신", a.huishin: "희신", a.gishin: "기신", a.gushin: "구신", a.hanshin: "한신"}[e]


def _gz_parts(gz: str) -> tuple[str, str, str, str]:
    """'癸卯' 또는 '癸卯(계묘)' → (천간 한자, 지지 한자, 천간 오행, 지지 오행)."""
    s, b = gz[0], gz[1]
    return s, b, ELEMENTS[STEM_ELEMENT[STEMS.index(s)]], ELEMENTS[BRANCH_ELEMENT[BRANCHES.index(b)]]


def _ko(gz: str) -> str:
    return _HANJA_KO[gz[0]] + _HANJA_KO[gz[1]]


class _Who:
    def __init__(self, r, name: str):
        n = (name or "").strip() or (getattr(r.chart.birth, "name", "") or "").strip()
        self.you = not n
        self.name = n or "너"
        self.female = r.chart.birth.gender == "여"

    def j(self, p: str) -> str:
        if self.you and p in ("이", "가"):
            return "네가"
        return _j(self.name, p)

    @property
    def poss(self) -> str:
        return "네" if self.you else self.name + "의"

    @property
    def to(self) -> str:
        return "너에게" if self.you else self.name + "에게"

    @property
    def spouse(self) -> str:
        return "관성" if self.female else "재성"

    @property
    def gender(self) -> str:
        return "여자" if self.female else "남자"


