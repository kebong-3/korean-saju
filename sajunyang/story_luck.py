def _join_reasons(rs: list[str]) -> str:
    """['재성이 들어왔고', '식상이 재물을 낳아 주고'] → '재성이 들어왔고, 식상이 재물을 낳아 주' (+'기 때문')."""
    txt = ", ".join(rs)
    return txt[:-1] if txt.endswith("고") else txt


def _why(f: str, sc: int, total: int, up: list[str], down: list[str]) -> str:
    U, Dn = _join_reasons(up), _join_reasons(down)
    if sc > total:
        s = f"총운({total}점)보다 높게 나온 건 {U}기 때문이다냥." if up else f"총운({total}점)보다 조금 높게 나왔다냥."
        return s + (f" 다만 {Dn}기에 조금 깎였다냥." if down else "")
    if sc < total:
        s = f"총운({total}점)보다 낮게 나온 건 {Dn}기 때문이다냥." if down else f"총운({total}점)보다 조금 낮게 나왔다냥."
        return s + (f" 그래도 {U}기에 바닥은 받쳐 준다냥." if up else "")
    if up and down:
        return f"{U}기에 오르고 {Dn}기에 내려서, {_j(f, '은')} 결국 총운({total}점)과 같은 자리에 선다냥."
    return f"{f} 쪽으론 특별히 더하거나 뺄 기운이 없어 총운({total}점) 흐름을 그대로 따라간다냥."


def _month_ref(m: dict) -> str:
    return f"{m['월']}월({m['간지']}·{m['십성']}, {m['점수']}점)"


def _month_story(r, m: dict, who: _Who) -> str:
    a = r.analysis
    seed = f"{_fp(r)}|m{m['월']}|{m['간지']}"
    sg, bg = m["십성"].split("/")
    t = _tier(m["점수"])
    s1 = f"{m['월']}월({m['절기']} {m['시작']}~)은 {m['간지']}({_ko(m['간지'])})월, 천간 {sg}·지지 {bg}의 달로 {m['점수']}점 — {MONTH_TONE[t]}."
    pos = (m["월"] - 2) % 12  # 寅월(2월)=0 … 丑월(1월)=11 — 10칸 뒤엔 같은 천간이 다시 온다
    v = (zlib.crc32(f"{_fp(r)}|{sg}".encode("utf-8")) + (pos >= 10)) % 2
    s2 = GOD_MONTH[sg][v]
    rels = m.get("작용", [])
    if rels:
        gs = _group_rels(rels)
        g = gs[0]
        if pos >= 10 and len(gs) > 1:  # 같은 천간의 앞선 달과 겹치지 않게 지지 쪽 작용을 앞세운다
            g = next((x for x in gs if x["chars"] or any(lab.endswith("지") for lab, _ in x["luck"])), gs[0])
        kind = _rel_kind(g)
        if g["chars"]:
            e = g["detail"][:1]
            role = _role(a, e) if e in ELEMENTS else "한신"
            s3 = f"원국과는 {_j(chr(183).join(g['chars']) + ' ' + kind + '(' + g['detail'] + ')', '이')} 일어나 {e} 기운이 모이는데, {who.to} {_j(role, '이라')} {ROLE_COMMENT[role]}냥."
        else:
            top, nch = min(g["natal"], key=lambda x: _POS_PRI.index(x[0]))
            pol = _pol(g)
            ch = g["luck"][0][1] if g["luck"] else ""
            if pos >= 10 and g["luck"] and g["luck"][0][0].endswith("간"):
                prev = (m["월"] - 11) % 12 + 1  # 10칸 앞(같은 천간)의 달
                s3 = (f"천간 {_j(ch, '은')} {prev}월과 같은 글자라 원국 {POS_NAME[top]} {_j(nch, '과')} 다시 {_j(kind, '을')} 이루니, "
                      f"{prev}월에 겪은 흐름을 떠올리며 미리 대비하면 된다냥.")
            else:
                s3 = f"월운의 {_j(ch, '이')} 원국 {POS_NAME[top]} {_j(nch, '과')} {_j(kind, '을')} 이루니 {POS_EFFECT[top][pol]}냥."
    else:
        s3 = f"원국과 크게 부딪히는 글자가 없어 지지 {bg} 기운이 조용히 바탕을 받쳐 준다냥."
    return " ".join([s1, s2, s3])


def month(r, m: dict, name: str = "") -> str:
    """yf['월별']의 한 달 이야기(2~3문장)."""
    return _month_story(r, m, _Who(r, name))


