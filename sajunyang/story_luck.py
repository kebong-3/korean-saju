def _parse_rel(s: str) -> dict:
    """'충: 시지 酉·일진지 卯' / '천간합: 연간 丁·월운간 壬 →목' / '반합: 卯·未 목국' → 구조체."""
    kind, _, rest = s.partition(": ")
    toks = rest.split("·")
    last = toks[-1].split(" ")
    if " " in toks[0]:
        members = toks[:-1] + [" ".join(last[:2])]
        detail = " ".join(last[2:])
        chars: list[str] = []
    else:
        members = []
        chars = toks[:-1] + [last[0]]
        detail = " ".join(last[1:])
    natal, luck = [], []
    for m in members:
        lab, _, ch = m.partition(" ")
        (natal if lab in _NATAL else luck).append((lab, ch))
    return {"kind": kind, "detail": detail, "natal": natal, "luck": luck, "chars": chars}


def _group_rels(strs: list[str]) -> list[dict]:
    groups: dict = {}
    order = []
    for s in strs:
        p = _parse_rel(s)
        key = (p["kind"], tuple(p["chars"]) if p["chars"] else tuple(ch for _, ch in p["luck"]), p["detail"])
        if key not in groups:
            groups[key] = {**p, "natal": []}
            order.append(key)
        for n in p["natal"]:
            if n not in groups[key]["natal"]:
                groups[key]["natal"].append(n)

    # 같은 글자쌍에 여러 작용(예: 충+형)이 걸리면 한 덩어리로 합친다
    merged: dict = {}
    morder = []
    for k in order:
        g = groups[k]
        g["kinds"] = [g["kind"] + ("(자형)" if g["kind"] == "형" and g["detail"] == "자형" else "")]
        mk = ("c", tuple(g["chars"]), g["kind"]) if g["chars"] else ("p", tuple(g["luck"]), tuple(g["natal"]))
        if mk in merged and not g["chars"]:
            merged[mk]["kinds"].append(g["kinds"][0])
            if not merged[mk]["detail"].startswith("→") and g["detail"].startswith("→"):
                merged[mk]["detail"] = g["detail"]
        else:
            merged[mk] = g
            morder.append(mk)
    groups, order = merged, morder

    def imp(g):
        pri = min([_POS_PRI.index(lab) for lab, _ in g["natal"]] or [9])
        k = g["kind"]
        kp = 0 if k in ("충", "육합", "천간합", "천간충") else 1 if k in ("형", "반합", "삼합", "방합", "원진") else 2
        return (kp, pri)
    return sorted((groups[k] for k in order), key=imp)


def _kname(k: str) -> str:
    return "자형" if k == "형(자형)" else k


def _rel_kind(g: dict) -> str:
    return "·".join(_kname(k) for k in g.get("kinds", [g["kind"]]))


def _pol(g: dict) -> int:
    ks = [_kname(k) for k in g.get("kinds", [g["kind"]])]
    if any(k in BAD_REL or k == "자형" for k in ks):
        return 1
    return 0 if any(k in GOOD_REL for k in ks) else 2


def _rel_sentence(g: dict, who: _Who, a, luck_name: str, seen: set | None = None) -> str:
    ks = [_kname(k) for k in g.get("kinds", [g["kind"]])]
    kind = ks[0]
    if len(ks) > 1:
        head = f"{_j(ks[0], '과')} {_j(ks[1], '이')} 한꺼번에 걸리는데"
    else:
        head = REL_SHORT.get(kind, f"{_j(kind, '은')} 원국을 건드리는 작용인데")
    if g["chars"]:
        chars = "·".join(g["chars"])
        e = g["detail"][:1] if g["detail"][:1] in ELEMENTS else ""
        if not e:
            return f"{head} {_j(chars, '이')} 모여 {_j(g['detail'] or '한 팀', '을')} 이룬다냥."
        role = _role(a, e)
        return (f"{head} {_j(chars, '이')} 모여 {_j(g['detail'], '을')} 이루니 {e} 기운이 세지는데, "
                f"{_j(e, '은')} {who.to} {_j(f'{role}({ROLE_EASY[role]})', '이라')} {ROLE_COMMENT[role]}냥.")
    ch = g["luck"][0][1] if g["luck"] else ""
    natal = "·".join(f"{lab} {c}" for lab, c in g["natal"])
    top = min((lab for lab, _ in g["natal"]), key=_POS_PRI.index) if g["natal"] else "일간"
    pol = _pol(g)
    s = f"{head} {luck_name}의 {_j(ch, '이')} 원국의 {_j(natal, '과')} 만나니 {POS_EFFECT[top][pol]}냥."
    if g["detail"].startswith("→") and g["detail"][1:2] in ELEMENTS:
        e = g["detail"][1]
        if seen is None or e not in seen:
            role = _role(a, e)
            s += f" 둘이 합해 생기는 {e} 기운은 {who.to} {_j(role, '이라')} {ROLE_COMMENT[role]}냥."
            if seen is not None:
                seen.add(e)
    return s


def _rel_lines(strs: list[str], who: _Who, a, luck_name: str, intro: str, max_groups: int = 2,
               seen: set | None = None) -> list[str]:
    """작용 목록 → [인용 문장, 그룹 설명 문장...]."""
    if not strs:
        return []
    shown = strs[:4]
    q = "」, 「".join(shown)
    more = f" 등 {len(strs)}가지" if len(strs) > 4 else ""
    out = [_j(f"{intro} 「{q}」{more}", "이다") + "냥."]
    seen = set() if seen is None else seen
    for g in _group_rels(strs)[:max_groups]:
        out.append(_rel_sentence(g, who, a, luck_name, seen))
    return out


def _count_rel(strs: list[str]) -> tuple[int, int]:
    kinds = [s.partition(":")[0] for s in strs]
    return sum(k in GOOD_REL for k in kinds), sum(k in BAD_REL for k in kinds)


def _has_pos(strs: list[str], pos: str, kinds: set) -> bool:
    for s in strs:
        p = _parse_rel(s)
        if p["kind"] in kinds and any(lab == pos for lab, _ in p["natal"]):
            return True
    return False


