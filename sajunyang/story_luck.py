class _Tales:
    def __init__(self, seed: str):
        self.seed = seed
        self.used: set = set()

    def take(self, pool: list[str], key: str) -> str:
        n = len(pool)
        start = zlib.crc32(f"{self.seed}|{key}".encode("utf-8")) % n
        for k in range(n):
            t = pool[(start + k) % n]
            if t not in self.used:
                self.used.add(t)
                return t
        return pool[start]


