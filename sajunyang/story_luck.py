def _lifestage(age: int) -> str:
    return "young" if age < 20 else "adult" if age < 60 else "senior"


def _age_now(r) -> int:
    c, t = r.chart, r.today
    return t.year - c.solar_date.year - ((t.month, t.day) < (c.solar_date.month, c.solar_date.day))


def _dw_rels(r, age: int) -> list[str]:
    for lp in getattr(r, "daewoon", []):
        if lp.start_age == age:
            return [re.sub(r"대운\d+", "대운", str(x)) for x in find_relations(r.chart.pillars, [lp.pillar])]
    return []


def _span(p: dict) -> str:
    return f"{p['나이']}~{p['나이'] + 9}세({p['시작']}~{p['시작'] + 9})"


