def _ko(p: Pillar) -> str:
    return STEMS_KO[p.stem] + BRANCHES_KO[p.branch]


def _top(names: list[str], n: int) -> list[str]:
    return sorted(names, key=lambda x: PRIORITY.index(x) if x in PRIORITY else 99)[:n]


def build(r, nat: dict, name: str, today: date) -> dict:
    """신살로 읽는 나: 한눈에 → 나를 이해하기 → 지나온 길 → 지금 → 앞으로 → 처방."""
    c = r.chart
    nm = name or "너"
    items = nat["목록"]
    kinds = {k: [i["이름"] for i in items if i["종류"] == k] for k in KIND_TXT}
    good = kinds["귀인"] + kinds["길성"]
    head = f"{nm}의 사주에는 도와주는 별 {len(good)}개, 양날의 칼 {len(kinds['살'])}개, 성향 별 {len(kinds['특수'])}개가 있다냥."
    head += (f" {', '.join(_top(good, 2))} 덕분에 사람과 배움에서 길이 열리는 편이다냥." if good
             else " 귀인 별이 적은 대신 스스로 길을 내는 힘이 큰 사주다냥.")
    if kinds["살"]:
        head += f" {', '.join(_top(kinds['살'], 2))}은 겁낼 게 아니라 잘 쓰면 무기가 되는 힘이다냥."
    me = []
    for i in sorted(items, key=lambda x: PRIORITY.index(x["이름"]) if x["이름"] in PRIORITY else 99)[:6]:
        info = INFO[i["이름"]]
        w = i["자리"][0]
        me.append({"이름": i["이름"], "종류": i["종류"],
                   "글": f"{info['한줄']} {POS_TXT[w[0]][0]}에 있어서 {POS_TXT[w[0]][1]}. {info['요즘']}",
                   "쓰는법": info["쓰는법"]})

    by = c.solar_date.year
    age = today.year - by - ((today.month, today.day) < (c.solar_date.month, c.solar_date.day))
    past, now, nxt = [], None, None
    for p in r.daewoon:
        inc = _top(SS.incoming(c, p.pillar), 3)
        row = {"나이": f"{p.start_age}~{p.start_age + 9}세", "시작": p.start_year, "간지": f"{p.pillar.hanja}({_ko(p.pillar)})",
               "신살": inc, "현재": p.current}
        if p.current:
            now = row
        elif p.start_age + 10 <= age and p.start_age <= age:
            past.append(row)
        elif p.start_age > age and nxt is None:
            nxt = row
    for row in past + ([now] if now else []) + ([nxt] if nxt else []):
        if row["신살"]:
            row["글"] = " ".join(f"{s}: {INFO[s]['운']}" for s in row["신살"][:2])
        else:
            row["글"] = "특별한 신살 없이 원국의 기운대로 흘러간 시기다냥."
    for row in past:
        s = row["신살"][0] if row["신살"] else None
        row["정리"] = (f"그 시절 '{s}'의 기운으로 겪은 일에서 얻은 것 한 가지를 적고, 아쉬운 건 '수고했다'로 닫아 주라냥."
                     if s else "그 시절의 나에게 '잘 버텼다' 한마디 해 주라냥.")
    years = []
    for y in range(today.year, today.year + 3):
        p = Pillar(year_index(y), f"{y}년")
        inc = _top(SS.incoming(c, p), 3)
        years.append({"연도": y, "간지": f"{p.hanja}({_ko(p)})", "신살": inc,
                      "준비": [f"{s}: {INFO[s]['준비']}" for s in inc[:2]] or ["큰 신살 없이 차분한 해 — 기본기를 다지는 해로 쓰라냥."]})
    if nxt:
        nxt["준비"] = [f"{s}: {INFO[s]['준비']}" for s in nxt["신살"][:2]] or ["원국의 힘대로 가는 10년 — 용신 습관을 꾸준히!"]
    rx = [{"이름": i["이름"], "처방": INFO[i["이름"]]["쓰는법"]} for i in
          sorted(items, key=lambda x: PRIORITY.index(x["이름"]) if x["이름"] in PRIORITY else 99)[:3]]
    return {"한눈에": head, "갯수": {k: len(v) for k, v in kinds.items()}, "나": me,
            "지나온길": past, "지금": {"대운": now, "올해": years[0] if years else None},
            "앞으로": {"다음대운": nxt, "3년": years}, "처방": rx, "메모": NOTES}


def luck_rows(r, today: date) -> dict:
    """만세력용 대운·세운·월운 줄(각 칸에 들어오는 신살 포함)."""
    c = r.chart
    dw = [{"나이": p.start_age, "시작": p.start_year, "간지": p.pillar.hanja, "한글": _ko(p.pillar),
           "천간십성": p.stem_god, "지지십성": p.branch_god, "운성": p.stage, "현재": p.current,
           "신살": SS.incoming(c, p.pillar), "12신살": SS.twelve_sinsal(c.year.branch, p.pillar.branch)}
          for p in r.daewoon]
    from ksaju.core import branch_main_stem, ten_god, twelve_stage
    ds = c.day_stem
    yrs = []
    for y in range(today.year - 5, today.year + 6):
        p = Pillar(year_index(y), f"{y}년")
        yrs.append({"연도": y, "나이": y - c.solar_date.year, "간지": p.hanja, "한글": _ko(p),
                    "천간십성": ten_god(ds, p.stem), "지지십성": ten_god(ds, branch_main_stem(p.branch)),
                    "운성": twelve_stage(ds, p.branch), "현재": y == today.year, "신살": SS.incoming(c, p),
                    "12신살": SS.twelve_sinsal(c.year.branch, p.branch)})
    ms = []
    now = datetime.combine(today, datetime.min.time()) + timedelta(hours=12)
    cur = max((k for k, m in enumerate(r.wolun) if m.start_kst <= now), default=-1)
    for k, m in enumerate(r.wolun):
        p = m.pillar
        ms.append({"절기": m.label.rstrip("~"), "시작": m.start_kst.strftime("%m.%d"), "간지": p.hanja, "한글": _ko(p),
                   "천간십성": m.stem_god, "지지십성": m.branch_god, "운성": twelve_stage(ds, p.branch),
                   "신살": SS.incoming(c, p), "현재": k == cur})
    return {"대운": dw, "세운": yrs, "월운": ms}
