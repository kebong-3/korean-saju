def _batchim(w: str) -> bool:
    ch = w.rstrip("'\")」 ")[-1:]
    return bool(ch) and "가" <= ch <= "힣" and (ord(ch) - 0xAC00) % 28 != 0


def _ga(w: str) -> str:
    return w + ("이" if _batchim(w) else "가")


def _ida(w: str) -> str:
    return w + ("이다냥" if _batchim(w) else "다냥")


def repr_q(w: str) -> str:
    return f"'{w}'"


def _personal(key: str, r) -> str:
    """이 구절을 '내 사주'에 비춰 본 한 줄."""
    a, c = r.analysis, r.chart
    d = r.to_dict()
    zero = [k for k, v in a.element_count.items() if not v] if isinstance(a.element_count, dict) else []
    try:
        if key == "중화":
            return "참고로 넌 '중화' 사주라 이미 밸런스 장인이다냥. 지금처럼만!" if a.strength.startswith("중화") else \
                f"너는 '{a.strength}' 쪽이라 이 구절이 숙제다냥. 보약 오행 {a.yongshin}{'으로' if _batchim(a.yongshin) and not a.yongshin.endswith(('ㄹ',)) else '로'} 균형 맞추기!"
        if key == "쇠왕":
            return f"참고로 너는 {_ida(repr_q(a.strength))}. {'든든한 엔진형' if '강' in a.strength else '팀플 최적화형' if '약' in a.strength else '밸런스형'}!"
        if key == "성정" and zero:
            return f"너는 {', '.join(zero)} 기운이 0개라 이 구절이 딱 네 얘기다냥. 빈칸 채우기부터!"
        if key == "월령":
            s = SEASON_OF.get(c.month.branch, "")
            return f"너는 {s}생, {SEASON_TIP[s]}." if s else ""
        if key == "길흉":
            return f"네 힐러 기운(희신)은 {_ida(a.huishin)}. 이 기운 닮은 사람을 곁에 두라냥!"
        if key == "용신":
            g = d["격국"]["이름"] if isinstance(d.get("격국"), dict) else str(a.gyeokguk)
            return f"너의 그릇은 {_ida(repr_q(g))}. 내 사주 탭 격국 장을 열어 보면 자세히 나온다냥."
        if key == "병약":
            return f"네 약(용신)은 {_ida(a.yongshin)}. 약점이 보이면 {a.yongshin} 기운 처방부터!"
        if key == "조후" and a.johu:
            return f"너는 조후로 {_ga(a.johu)} 필요한 사주라 이 구절이 찰떡이다냥."
    except Exception:  # noqa: BLE001
        return ""
    return ""


def _ganji_year(r, y: int) -> dict:
    p = Pillar(year_index(y), f"{y}년")
    s, rels, _ = _pillar_score(r.chart, r.analysis, p)
    sg = ten_god(r.chart.day_stem, p.stem)
    return {"연도": y, "간지": p.hanja, "한글": p.hangul, "십성": sg, "그룹": GROUP[sg], "점수": _clamp(s),
            "테마": YEAR_THEME[sg][0], "작용": [str(x) for x in rels][:2]}


def _dw_at(dws: list[dict], y: int) -> dict | None:
    cur = None
    for d in dws:
        if d["시작"] <= y:
            cur = d
    return cur


def past(r, fx: dict, today: date) -> list[dict]:
    """만 7세 무렵부터 작년까지, 최근 해가 먼저 오게."""
    by = r.chart.birth.year
    out = []
    for y in range(today.year - 1, max(by + 6, today.year - 60) - 1, -1):
        e = _ganji_year(r, y)
        dw = _dw_at(fx["평생운"]["대운"], y)
        e.update({"나이": y - by, "대운": f"{dw['나이']}세 {dw['간지']}" if dw else "", "질문": list(ASK[e["십성"]])})
        out.append(e)
    return out


def future(r, fx: dict, today: date, n: int = 3) -> list[dict]:
    """올해 + 앞으로 n년(가을 이후엔 올해가 거의 끝났으니 한 해 더)."""
    yong = fx["개운법"]
    out = []
    for y in range(today.year, today.year + n + (1 if today.month >= 9 else 0)):
        e = _ganji_year(r, y)
        kw, prep, care = PREP[e["십성"]]
        dw = _dw_at(fx["평생운"]["대운"], y)
        e.update({"나이": y - r.chart.birth.year, "키워드": kw, "준비": prep, "조심": care,
                  "대운": f"{dw['나이']}세 {dw['간지']}" if dw else "",
                  "한마디": YEAR_THEME[e["십성"]][1], "개운": (yong.get("처방") or [{}])[0].get("내용", "")})
        out.append(e)
    return out


def wisdom(r, today: date, seed: str = "") -> dict:
    """오늘의 명리 한 구절(사주냥이식 재해석). 날짜+사람으로 돌리고, 월요일엔 이 사람에게 특히 맞는 구절을 우선."""
    items = [{**w, "나에게": _personal(w["key"], r)} for w in WISDOM]
    h = int(hashlib.md5(f"{seed}:{today.isoformat()}".encode()).hexdigest(), 16)
    mine = [i for i, w in enumerate(items) if w["나에게"] and w["key"] in ("중화", "성정", "조후", "병약")]
    k = mine[h % len(mine)] if mine and today.weekday() == 0 else h % len(items)
    return {**items[k], "오늘": k, "전체": items}


def build(r, fx: dict, today: date, seed: str = "") -> dict:
    return {"지난해들": past(r, fx, today), "앞으로": future(r, fx, today), "한구절": wisdom(r, today, seed)}
