def _j(word: str, a: str, b: str) -> str:
    """받침 있으면 a(은·이·과), 없으면 b(는·가·와)."""
    ch = word[-1] if word else ""
    has = "가" <= ch <= "힣" and (ord(ch) - 0xAC00) % 28 != 0
    return word + (a if has else b)


