def household(weights: list[dict]) -> dict:
    """가족 모두의 오행 비중을 더해 우리 집 오행을 본다."""
    tot = {e: 0.0 for e in "목화토금수"}
    for w in weights:
        for e in tot:
            tot[e] += w.get(e, 0)
    s = sum(tot.values()) or 1
    pct = {e: round(v / s * 100) for e, v in tot.items()}
    many, few = max(pct, key=pct.get), min(pct, key=pct.get)
    e, name, desc = HOME_TYPE[many]
    return {"오행": pct, "많은": many, "부족": few, "이름": name, "이모지": e, "설명": desc,
            "처방": f"우리 집엔 {few} 기운이 부족하다냥 → {HOME_RX[few]}.", "주의": HOME_TOO[many]}


