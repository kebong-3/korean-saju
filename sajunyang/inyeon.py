def is_legend(m: dict) -> bool:
    """전설의 황금방울 냥: 천을귀인 자리에 + 케미 85 이상 — 약 스무 명 중 한 명(천을귀인만으로는 세 명 중 한 명꼴이라 너무 흔하다)."""
    return bool(m["나에게"].get("천을귀인")) and m.get("케미", 0) >= 85


def moon(chem: int) -> dict:
    for cut, e, n, d in MOONS:
        if chem >= cut:
            return {"이모지": e, "이름": n, "설명": d}
    return {}


def dex(members: list[dict]) -> dict:
    """인연 도감: 다섯 냥이 중 몇 마리를 만났는지 + 전설의 황금방울 냥."""
    met = [k for k in CHAR if any(m["나에게"]["키"] == k for m in members)]
    legend = [m["이름"] for m in members if is_legend(m)]
    n = len(met)
    _, title, say = next(t for t in DEX_TITLES if n >= t[0])
    if legend:
        say += f" 게다가 전설의 황금방울 냥({', '.join(legend[:2])})까지 만났어! 🔔"
    return {"만남": met, "수": n, "전체": len(CHAR), "칭호": title, "말": say, "전설": legend}


def today_pick(members: list[dict], today) -> dict | None:
    """오늘의 인연: 오늘 일진(일간) 기운이 살려 주는(生) 오행을 가진 사람 → 오늘 연락하면 말이 잘 통하는 사람."""
    if not members:
        return None
    from ksaju.core import STEM_ELEMENT, Pillar, day_index
    day_el = STEM_ELEMENT[Pillar(day_index(today), "").stem]
    target = (day_el + 1) % 5  # 오늘 기운이 생(生)해 주는 오행
    def score(m):
        e = EL_NAMES.find(m.get("유형", {}).get("오행", ""))
        s = 3 if e == target else 2 if e == day_el else 0
        return (s, (hash_day(today) + sum(map(ord, m["이름"]))) % 97)
    m = max(members, key=score)
    e = EL_NAMES.find(m.get("유형", {}).get("오행", ""))
    if e == target:
        why = f"오늘은 {EL_NAMES[day_el]}의 날 — {EL_NAMES[day_el]} 기운이 {m['유형']['오행']} 기운을 살려 주니까, {_n(m)}의 마음이 활짝 열리는 날이다냥."
    elif e == day_el:
        why = f"오늘은 {EL_NAMES[day_el]}의 날 — {_j(_n(m), '과', '와')} 같은 기운이 흐르는 날이라 말이 척척 통한다냥."
    else:
        why = f"오늘은 {EL_NAMES[day_el]}의 날 — 냥이 방울이 {_j(_n(m), '을', '를')} 가리켰다냥. 오랜만에 안부 한 줄 어때?"
    k = m["나에게"]["키"]
    polite = m.get("관계") in ("boss",)
    return {"이름": m["이름"], "id": m.get("id"), "캐릭터": CHAR[k][1] + " " + CHAR[k][0], "이유": why,
            "한마디": HELLO[k][1 if polite else 0], "오늘기운": EL_NAMES[day_el]}


def hash_day(d) -> int:
    return d.toordinal() * 7919 % 101


