    w = None
    if work:
        best = max(work, key=lambda m: m["케미"])
        w = {"인원": len(work), "찰떡": {"이름": best["이름"], "케미": best["케미"]}}
        bosses = [m for m in work if m.get("관계") == "boss"]
        tg = [_n(m) for m in bosses if m["나에게"]["키"] == "tiger"]
        gu = [_n(m) for m in bosses if m["나에게"]["키"] == "guiin"]
