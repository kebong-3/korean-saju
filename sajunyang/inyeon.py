def _facts(view: dict) -> dict:
    """사주로 계산해 둔 두 사람의 관계 문장(좋은점·아쉬운점)에서 근거를 뽑는다."""
    import re
    f = {"일간": None, "나쁜": [], "좋은": [], "보약": None, "부족": None, "부담": None}
    for s in list(view.get("좋은점", [])) + list(view.get("아쉬운점", [])):
        head, _, body = s.partition(":")
        body = body.strip()
        tok = body.split(" ")[0] if body else ""
        if head == "일간":
            f["일간"] = ("합" if body.startswith("천간합") else "충" if body.startswith("천간충") else "same" if body.startswith("같은 오행")
                        else ("them_give" if "상대" in body.split("—")[-1][:5] else "me_give") if "살려 줌" in body
                        else ("them_lead" if "상대" in body.split("—")[-1][:5] else "me_lead") if "누름" in body else None)
        elif head.startswith("일지") or head == "띠":
            w = "일지" if head.startswith("일지") else "띠"
            bad = next((k for k in ("원진", "충", "형", "해", "파") if tok == k), None)
            if bad:
                f["나쁜"].append((w, bad))
            else:
                good = next((k for k in GOOD_NEAR if tok.startswith(k)), None)
                if good:
                    f["좋은"].append((w, good))
        elif "내 보약(용신)" in s and "넉넉히" in s:
            m = re.search(r"용신\) (\S) 기운", s)
            f["보약"] = m and m.group(1)
        elif "거의 없는" in s:
            m = re.search(r"없는 (\S+) 기운", s)
            f["부족"] = m and m.group(1)
