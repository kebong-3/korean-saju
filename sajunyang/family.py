def _title(f: _Fam) -> str:
    p, c = f.p, f.c
    k = f.kind
    if k == "같음":
        core = SAME_TITLE[p.de]
    elif k == "생12":
        core = GEN_TITLE[p.de](p.img, c.img)
    elif k == "생21":
        core = GEN_TITLE[c.de](c.img, p.img)
    elif k in ("극12", "극21"):
        a, b = (p, c) if k == "극12" else (c, p)
        core = CTRL_TITLE[a.de](a.img, b.img)
    elif k == "합":
        core = f"손을 맞잡은 {jo(p.img, '와과')} {c.img}"
    else:
        core = f"마주 보고 선 {jo(p.img, '와과')} {c.img}"
    return f"{core} — {jo(f.role, '와과')} {f.kid}"


