class _Fam:
    def __init__(self, rp, rc, names, today: date):
        names = list(names or [])
        while len(names) < 2:
            names.append("")
        self.p = _P(rp, names[0] if isinstance(names[0], str) else "", "너")
        self.c = _P(rc, names[1] if isinstance(names[1], str) else "", "아이")
        if self.p.name == self.c.name:
            self.c.name = "아이" if self.p.name != "아이" else "우리 아이"
        self.today = today
        self.role = "아빠" if self.p.gender == "남" else "엄마"
        self.kid = "아들" if self.c.gender == "남" else "딸"
        self.age = _age(self.c.c.solar_date, today)
        self.stage = _stage(self.age)
        self.kind = _stem_kind(self.p.ds, self.c.ds)  # 생12 = 부모가 아이를 생
        self.btype = BOND_TYPE[self.kind]
        self.pgrp = max(self.p.a.group_weight, key=self.p.a.group_weight.get)
        self.cgrp = max(self.c.a.group_weight, key=self.c.a.group_weight.get)
        self.key = f"{self.p.c.day.index}-{self.c.c.day.index}-{self.p.yb}-{self.c.yb}-{self.stage}"
        ys = seun(self.c.c, today.year, today.year + 1)
        ps = seun(self.p.c, today.year, today.year)
        self.cy = ys
        self.py = ps[0]

    @property
    def young(self) -> bool:
        return self.stage in ("영유아", "초등")


def _ctl_pair(f: _Fam):
    """극 관계에서 (다스리는 쪽, 다스림 받는 쪽)."""
    p, c = f.p, f.c
    return (p, c) if (c.de - p.de) % 5 == 2 else (c, p)


