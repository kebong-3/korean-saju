def card(stem: int, branch: int) -> dict:
    s, b = STEMS[stem], BRANCHES[branch]
    noun, keys, sline = STEM[s]
    adj, animal, bkey, bline = BRANCH[b]
    el = ELEMENTS[STEM_ELEMENT[stem]]
    return {
        "일주": f"{s}{b}", "한글": f"{STEMS_KO[stem]}{BRANCHES_KO[branch]}",
        "이름": f"{adj} {noun} 냥이", "동물": animal,
        "키워드": [keys[0], keys[1], bkey],
        "한줄": f"{sline}, {bline} 사람이다냥.",
        "오행": el, "색": EL_COLOR[el], "옷": EL_OUTFIT[el],
    }


def of_reading(r) -> dict:
    return card(r.chart.day.stem, r.chart.day.branch)
